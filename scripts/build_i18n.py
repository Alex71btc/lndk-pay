#!/usr/bin/env python3
"""Validate central UI catalogs and build deterministic synchronous browser assets.

Run `python3 scripts/build_i18n.py --check` in CI. No external packages required.
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app" / "i18n"
OUTPUT = ROOT / "app" / "assets" / "i18n"
LANGUAGES = ("en", "de", "es", "fr", "pl")
PLACEHOLDER = re.compile(r"\{([A-Za-z][A-Za-z0-9_]*)\}")


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate translation key: {key}")
        result[key] = value
    return result


def read_catalog(path):
    data = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique_object)
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a flat key/value object")
    for key, value in data.items():
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_.-]*", key):
            raise ValueError(f"{path}: invalid key {key!r}")
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"{path}: {key} must be a nonempty string")
        if re.search(r"</?[A-Za-z][^>]*>", value):
            raise ValueError(f"{path}: {key} contains markup; keep markup in the page")
    return data


def load_scope(directory):
    translations = {language: read_catalog(directory / f"{language}.json")
                    for language in LANGUAGES}
    english = translations["en"]
    for language, catalog in translations.items():
        missing = english.keys() - catalog.keys()
        extra = catalog.keys() - english.keys()
        if missing or extra:
            raise ValueError(f"{directory.name}/{language}: missing={sorted(missing)}, extra={sorted(extra)}")
        for key, value in catalog.items():
            if set(PLACEHOLDER.findall(value)) != set(PLACEHOLDER.findall(english[key])):
                raise ValueError(f"{directory.name}/{language}: placeholder mismatch in {key}")
    return translations


def write_product(destination, content, check):
    if check:
        if not destination.exists() or destination.read_text(encoding="utf-8") != content:
            raise ValueError(f"{destination.relative_to(ROOT)} is stale; run scripts/build_i18n.py")
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")


def build(check=False, names=()):
    if not SOURCE.is_dir():
        raise ValueError("No central translation catalogs found")
    scopes = [SOURCE / name for name in names] or sorted(
        directory for directory in SOURCE.iterdir() if directory.is_dir()
    )
    for directory in scopes:
        translations = load_scope(directory)
        serialized = json.dumps(translations, ensure_ascii=False, sort_keys=True, indent=2)
        content = (
            "// Generated by scripts/build_i18n.py; edit app/i18n instead.\n"
            f"window.Bolt12I18n.register({json.dumps(directory.name)}, {serialized});\n"
        )
        if directory.name == "intent":
            # The payment link page must not load subresources (including scripts)
            # before removing the Lightning target from the address bar.
            page = ROOT / "app/frontend/admin/pay-intent.html"
            html = page.read_text(encoding="utf-8")
            start = "<!-- BEGIN generated i18n: scripts/build_i18n.py -->"
            end = "<!-- END generated i18n -->"
            before, marker, tail = html.partition(start)
            _, closing, after = tail.partition(end)
            if not marker or not closing:
                raise ValueError(f"{page}: missing inline catalog markers")
            runtime = (OUTPUT / "runtime.js").read_text(encoding="utf-8")
            inline = f'\n<script>\n{runtime}\n{content}Bolt12I18n.use("intent");\n</script>\n'
            write_product(page, before + start + inline + end + after, check)
        else:
            write_product(OUTPUT / f"{directory.name}.js", content, check)
        print(f"{directory.name}: {len(translations['en'])} keys × {len(LANGUAGES)} languages OK")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--scope", action="append", default=[], help="Build only this page scope")
    args = parser.parse_args()
    try:
        build(check=args.check, names=args.scope)
    except (OSError, ValueError) as error:
        parser.exit(1, f"i18n validation failed: {error}\n")
